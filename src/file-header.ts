import { VERSION } from "./types.js";

function optsString(opts: Record<string, unknown>): string {
  const pairs = Object.entries(opts)
    .filter(([, v]) => v !== undefined && v !== false)
    .map(([k, v]) => `${k}=${typeof v === "string" ? `"${v}"` : v}`);
  return pairs.length ? `Options: ${pairs.join(", ")}` : "";
}

export function buildScssHeader(fn: string, primaryHex: string, opts?: Record<string, unknown>, timestamp?: string): string {
  const lines = [
    `Generated by salt-theme-gen v${VERSION}`,
    `Function: ${fn}`,
    `Primary: ${primaryHex}`,
  ];
  const o = opts ? optsString(opts) : "";
  if (o) lines.push(o);
  if (timestamp) lines.push(`Generated: ${timestamp}`);
  return lines.map((l) => `// ${l}`).join("\n") + "\n";
}

export function buildCssHeader(fn: string, primaryHex: string, opts?: Record<string, unknown>, timestamp?: string): string {
  const lines = [
    `Generated by salt-theme-gen v${VERSION}`,
    `Function: ${fn}`,
    `Primary: ${primaryHex}`,
  ];
  const o = opts ? optsString(opts) : "";
  if (o) lines.push(o);
  if (timestamp) lines.push(`Generated: ${timestamp}`);
  return `/*\n${lines.map((l) => ` * ${l}`).join("\n")}\n */\n`;
}

export function buildJsonDescription(fn: string, primaryHex: string, opts?: Record<string, unknown>, timestamp?: string): string {
  const parts = [
    `Generated by salt-theme-gen v${VERSION}`,
    `Function: ${fn}`,
    `Primary: ${primaryHex}`,
  ];
  const o = opts ? optsString(opts) : "";
  if (o) parts.push(o);
  if (timestamp) parts.push(timestamp);
  return parts.join(" · ");
}
