import { VERSION } from "./types.js";

function optsString(opts: Record<string, unknown>): string {
  const pairs = Object.entries(opts)
    .filter(([, v]) => v !== undefined && v !== false)
    .map(([k, v]) => `${k}=${typeof v === "string" ? `"${v}"` : v}`);
  return pairs.length ? `Options: ${pairs.join(", ")}` : "";
}

export function buildCssHeader(fn: string, primaryHex: string, opts?: Record<string, unknown>): string {
  const lines = [
    `Generated by salt-theme-gen v${VERSION}`,
    `Function: ${fn}`,
    `Primary: ${primaryHex}`,
  ];
  const o = opts ? optsString(opts) : "";
  if (o) lines.push(o);
  lines.push(`Generated: ${new Date().toISOString()}`);
  return `/*\n${lines.map((l) => ` * ${l}`).join("\n")}\n */\n`;
}

export function buildJsonDescription(fn: string, primaryHex: string, opts?: Record<string, unknown>): string {
  const parts = [
    `Generated by salt-theme-gen v${VERSION}`,
    `Function: ${fn}`,
    `Primary: ${primaryHex}`,
  ];
  const o = opts ? optsString(opts) : "";
  if (o) parts.push(o);
  parts.push(new Date().toISOString());
  return parts.join(" · ");
}
