import { describe, it, expect, beforeAll } from "vitest";
import { generateScssVariables } from "./scss.js";
import { generateTheme } from "./generate-theme.js";
import type { ScssVariablesResult } from "./scss.js";

const theme = generateTheme({ primary: "#6366f1" });

// ─── Structure ───────────────────────────────────────────────────────

describe("generateScssVariables — structure", () => {
  let result: ScssVariablesResult;

  beforeAll(() => { result = generateScssVariables(theme); });

  it("scss starts with SCSS line-comment header", () => {
    expect(result.scss).toMatch(/^\/\/ Generated by salt-theme-gen v[\d.a-z-]+/);
    expect(result.scss).toContain("// Function: generateScssVariables");
    expect(result.scss).toContain("// Primary: #");
    expect(result.scss).not.toContain("// Generated: 20");
  });

  it("scss contains light and dark section comments", () => {
    expect(result.scss).toContain("// ─── Light mode");
    expect(result.scss).toContain("// ─── Dark mode");
  });

  it("light section precedes dark section in scss", () => {
    expect(result.scss.indexOf("// ─── Light mode")).toBeLessThan(
      result.scss.indexOf("// ─── Dark mode")
    );
  });

  it("header does not appear in light or dark fields", () => {
    expect(result.light).not.toContain("Generated by");
    expect(result.dark).not.toContain("Generated by");
  });

  it("scss contains all light declarations", () => {
    expect(result.scss).toContain(result.light.split("\n")[0]);
  });

  it("scss contains all dark declarations", () => {
    expect(result.dark.split("\n").slice(0, 3).every((l) => result.scss.includes(l))).toBe(true);
  });
});

// ─── Light variables ─────────────────────────────────────────────────

describe("generateScssVariables — light variables", () => {
  const { light } = generateScssVariables(theme);

  it("uses $ prefix for all variables", () => {
    for (const line of light.split("\n").filter(Boolean)) {
      expect(line).toMatch(/^\$/);
    }
  });

  it("emits semantic color variables without suffix", () => {
    expect(light).toContain("$salt-color-primary: #");
    expect(light).toContain("$salt-color-secondary: #");
    expect(light).toContain("$salt-color-background: #");
    expect(light).toContain("$salt-color-on-primary: #");
    expect(light).toContain("$salt-color-on-background: #");
  });

  it("converts camelCase to kebab-case", () => {
    expect(light).toContain("$salt-color-on-primary:");
    expect(light).not.toContain("$salt-color-onPrimary:");
    expect(light).toContain("$salt-color-on-muted:");
  });

  it("includes all 26 semantic colors", () => {
    const matches = (light.match(/\$salt-color-[a-z-]+: #/g) ?? []);
    expect(matches.length).toBeGreaterThanOrEqual(26);
  });

  it("includes surface elevation variables", () => {
    expect(light).toContain("$salt-surface-");
  });

  it("includes state variables (8 intents × 4 states)", () => {
    const intents = ["primary", "secondary", "tertiary", "quaternary", "danger", "success", "warning", "info"];
    const states  = ["hover", "pressed", "focused", "disabled"];
    for (const intent of intents) {
      for (const state of states) {
        expect(light).toContain(`$salt-state-${intent}-${state}: #`);
      }
    }
  });

  it("spacing uses px", () => {
    expect(light).toMatch(/\$salt-spacing-\w+: \d+px;/);
  });

  it("radius uses px", () => {
    expect(light).toMatch(/\$salt-radius-\w+: \d+px;/);
  });

  it("font-size uses rem", () => {
    expect(light).toMatch(/\$salt-font-size-\w+: [\d.]+rem;/);
  });

  it("icon-size uses rem", () => {
    expect(light).toMatch(/\$salt-icon-size-\w+: [\d.]+rem;/);
  });

  it("control sizes use px", () => {
    expect(light).toMatch(/\$salt-control-\w+: \d+px;/);
  });

  it("breakpoints use px", () => {
    expect(light).toMatch(/\$salt-breakpoint-\w+: \d+px;/);
  });

  it("font family variables are present", () => {
    expect(light).toContain("$salt-font-family-sans:");
    expect(light).toContain("$salt-font-family-display:");
  });

  it("typography size/line-height/weight/letter-spacing variables present", () => {
    expect(light).toContain("$salt-type-body-medium-size:");
    expect(light).toContain("$salt-type-body-medium-line-height:");
    expect(light).toContain("$salt-type-body-medium-weight:");
    expect(light).toContain("$salt-type-body-medium-letter-spacing:");
    expect(light).toContain("$salt-type-body-medium-family:");
  });
});

// ─── Dark variables ──────────────────────────────────────────────────

describe("generateScssVariables — dark variables", () => {
  const { dark } = generateScssVariables(theme);

  it("dark color vars have -dark suffix", () => {
    expect(dark).toContain("$salt-color-primary-dark: #");
    expect(dark).toContain("$salt-color-background-dark: #");
    expect(dark).toContain("$salt-color-on-primary-dark: #");
  });

  it("dark does not contain token vars (spacing, radius, etc.)", () => {
    expect(dark).not.toContain("$salt-spacing-");
    expect(dark).not.toContain("$salt-radius-");
    expect(dark).not.toContain("$salt-font-size-");
  });

  it("dark background differs from light background", () => {
    const result = generateScssVariables(theme);
    const lightBg = result.light.match(/\$salt-color-background: (#[0-9a-f]{6})/)?.[1];
    const darkBg  = result.dark.match(/\$salt-color-background-dark: (#[0-9a-f]{6})/)?.[1];
    expect(lightBg).toBeDefined();
    expect(darkBg).toBeDefined();
    expect(lightBg).not.toBe(darkBg);
  });

  it("dark primary differs from light primary", () => {
    const result = generateScssVariables(theme);
    const lp = result.light.match(/\$salt-color-primary: (#[0-9a-f]{6})/)?.[1];
    const dp = result.dark.match(/\$salt-color-primary-dark: (#[0-9a-f]{6})/)?.[1];
    expect(lp).not.toBe(dp);
  });
});

// ─── Palettes ────────────────────────────────────────────────────────

describe("generateScssVariables — includePalettes option", () => {
  it("palettes absent by default", () => {
    const { light, dark } = generateScssVariables(theme);
    expect(light).not.toContain("$salt-palette-");
    expect(dark).not.toContain("$salt-palette-");
  });

  it("palettes present when includePalettes: true", () => {
    const { light, dark } = generateScssVariables(theme, { includePalettes: true });
    expect(light).toContain("$salt-palette-primary-50:");
    expect(light).toContain("$salt-palette-primary-950:");
    expect(dark).toContain("$salt-palette-primary-50-dark:");
    expect(dark).toContain("$salt-palette-primary-950-dark:");
  });

  it("includePalettes emits 8 × 11 = 88 palette vars per mode", () => {
    const { light, dark } = generateScssVariables(theme, { includePalettes: true });
    const lightCount = (light.match(/\$salt-palette-/g) ?? []).length;
    const darkCount  = (dark.match(/\$salt-palette-/g) ?? []).length;
    expect(lightCount).toBe(88);
    expect(darkCount).toBe(88);
  });
});

// ─── Prefix option ───────────────────────────────────────────────────

describe("generateScssVariables — prefix option", () => {
  it("custom prefix replaces salt", () => {
    const { light, dark } = generateScssVariables(theme, { prefix: "ds" });
    expect(light).toContain("$ds-color-primary:");
    expect(light).not.toContain("$salt-");
    expect(dark).toContain("$ds-color-primary-dark:");
  });

  it("header shows prefix option when non-default", () => {
    const { scss } = generateScssVariables(theme, { prefix: "ds" });
    expect(scss).toContain('prefix="ds"');
  });
});

// ─── Consistency ─────────────────────────────────────────────────────

describe("generateScssVariables — consistency", () => {
  it("light and dark are consistent across calls", () => {
    const r1 = generateScssVariables(theme);
    const r2 = generateScssVariables(theme);
    expect(r1.light).toBe(r2.light);
    expect(r1.dark).toBe(r2.dark);
  });

  it("all presets produce valid output", () => {
    const presets = ["peacock", "ocean", "forest", "desert", "aurora"] as const;
    for (const preset of presets) {
      const t = generateTheme({ preset });
      const { light, dark } = generateScssVariables(t);
      expect(light).toContain("$salt-color-primary:");
      expect(dark).toContain("$salt-color-primary-dark:");
    }
  });
});
