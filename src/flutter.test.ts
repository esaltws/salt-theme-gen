import { describe, it, expect } from "vitest";
import { generateFlutterTheme } from "./flutter.js";
import { generateTheme } from "./generate-theme.js";
import type { FlutterThemeResult } from "./flutter.js";

const theme = generateTheme({ primary: "#6366f1" });
const result: FlutterThemeResult = generateFlutterTheme(theme);

// ─── Structure ───────────────────────────────────────────────────────

describe("generateFlutterTheme — structure", () => {
  it("dart starts with a line-comment header", () => {
    expect(result.dart).toMatch(/^\/\/ Generated by salt-theme-gen v[\d.a-z-]+/);
    expect(result.dart).toContain("// Function: generateFlutterTheme");
    expect(result.dart).toContain("// Primary: #");
  });

  it("dart imports flutter/material.dart", () => {
    expect(result.dart).toContain("import 'package:flutter/material.dart';");
  });

  it("dart contains the default class SaltTheme", () => {
    expect(result.dart).toContain("class SaltTheme {");
    expect(result.dart).toContain("SaltTheme._();");
  });

  it("dart contains light and dark section comments", () => {
    expect(result.dart).toContain("// ─── Light mode");
    expect(result.dart).toContain("// ─── Dark mode");
    expect(result.dart).toContain("// ─── Tokens");
  });

  it("header does not appear in light or dark fields", () => {
    expect(result.light).not.toContain("Generated by");
    expect(result.dark).not.toContain("Generated by");
  });
});

// ─── Light mode ──────────────────────────────────────────────────────

describe("generateFlutterTheme — light constants", () => {
  it("primary is Color(0xFF...) format", () => {
    expect(result.light).toMatch(/static const Color primary = Color\(0xFF[0-9A-F]{6}\);/);
  });

  it("contains all 26 semantic color constants (no suffix)", () => {
    const expected = [
      "primary", "secondary", "tertiary", "quaternary",
      "background", "surface", "text", "muted", "border", "input", "ring",
      "danger", "success", "warning", "info",
      "on_primary", "on_secondary", "on_tertiary", "on_quaternary",
      "on_background", "on_surface", "on_muted",
      "on_danger", "on_success", "on_warning", "on_info",
    ];
    for (const name of expected) {
      expect(result.light).toContain(`static const Color ${name} =`);
    }
  });

  it("surface elevation constants present (surfaceCard etc.)", () => {
    expect(result.light).toContain("static const Color surfaceCard =");
    expect(result.light).toContain("static const Color surfacePopover =");
  });

  it("state constants use intent_state naming", () => {
    expect(result.light).toContain("static const Color primary_hover =");
    expect(result.light).toContain("static const Color danger_disabled =");
  });

  it("light constants have no Dark suffix", () => {
    expect(result.light).not.toContain("Dark =");
  });
});

// ─── Dark mode ───────────────────────────────────────────────────────

describe("generateFlutterTheme — dark constants", () => {
  it("dark primary has Dark suffix", () => {
    expect(result.dark).toMatch(/static const Color primaryDark = Color\(0xFF[0-9A-F]{6}\);/);
  });

  it("contains all 26 semantic colors with Dark suffix", () => {
    const expected = ["primaryDark", "backgroundDark", "on_primaryDark", "dangerDark"];
    for (const name of expected) {
      expect(result.dark).toContain(`static const Color ${name} =`);
    }
  });

  it("dark background differs from light background", () => {
    const lBg = result.light.match(/static const Color background = (Color\([^)]+\))/)?.[1];
    const dBg = result.dark.match(/static const Color backgroundDark = (Color\([^)]+\))/)?.[1];
    expect(lBg).toBeDefined();
    expect(dBg).toBeDefined();
    expect(lBg).not.toBe(dBg);
  });

  it("dark does not contain token constants", () => {
    expect(result.dark).not.toContain("static const double spacing");
    expect(result.dark).not.toContain("static const double radius");
  });
});

// ─── Token constants ─────────────────────────────────────────────────

describe("generateFlutterTheme — token constants", () => {
  it("dart contains spacing as double", () => {
    expect(result.dart).toMatch(/static const double spacingMd = \d+;/);
  });

  it("dart contains radius as double", () => {
    expect(result.dart).toMatch(/static const double radius\w+ = \d+;/);
  });

  it("dart contains fontSize as double", () => {
    expect(result.dart).toMatch(/static const double fontSize\w+ = \d+/);
  });

  it("dart contains fontSizeBase", () => {
    expect(result.dart).toContain("static const double fontSizeBase =");
  });

  it("dart contains iconSize as double", () => {
    expect(result.dart).toMatch(/static const double iconSize\w+ = \d+/);
  });

  it("dart contains fontWeight as int", () => {
    expect(result.dart).toMatch(/static const int fontWeight\w+ = \d+;/);
  });

  it("dart contains lineHeight as double", () => {
    expect(result.dart).toMatch(/static const double lineHeight\w+ = [\d.]+;/);
  });
});

// ─── className option ────────────────────────────────────────────────

describe("generateFlutterTheme — className option", () => {
  it("custom className replaces SaltTheme", () => {
    const { dart } = generateFlutterTheme(theme, { className: "AppTheme" });
    expect(dart).toContain("class AppTheme {");
    expect(dart).toContain("AppTheme._();");
    expect(dart).not.toContain("SaltTheme");
  });

  it("header shows className when non-default", () => {
    const { dart } = generateFlutterTheme(theme, { className: "AppTheme" });
    expect(dart).toContain('className="AppTheme"');
  });
});

// ─── Consistency ─────────────────────────────────────────────────────

describe("generateFlutterTheme — consistency", () => {
  it("light and dark are consistent across calls", () => {
    const r1 = generateFlutterTheme(theme);
    const r2 = generateFlutterTheme(theme);
    expect(r1.light).toBe(r2.light);
    expect(r1.dark).toBe(r2.dark);
  });

  it("all presets produce valid dart output", () => {
    const presets = ["peacock", "ocean", "forest", "desert"] as const;
    for (const preset of presets) {
      const t = generateTheme({ preset });
      const { dart } = generateFlutterTheme(t);
      expect(dart).toContain("class SaltTheme");
      expect(dart).toContain("static const Color primary =");
    }
  });
});
