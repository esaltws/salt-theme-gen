import { describe, it, expect } from "vitest";
import { generateSwiftUITheme } from "./swiftui.js";
import { generateTheme } from "./generate-theme.js";
import type { SwiftUIThemeResult } from "./swiftui.js";

const theme = generateTheme({ primary: "#6366f1" });
const result: SwiftUIThemeResult = generateSwiftUITheme(theme);

// ─── Structure ───────────────────────────────────────────────────────

describe("generateSwiftUITheme — structure", () => {
  it("swift starts with a line-comment header", () => {
    expect(result.swift).toMatch(/^\/\/ Generated by salt-theme-gen v[\d.a-z-]+/);
    expect(result.swift).toContain("// Function: generateSwiftUITheme");
    expect(result.swift).toContain("// Primary: #");
  });

  it("swift imports SwiftUI", () => {
    expect(result.swift).toContain("import SwiftUI");
  });

  it("swift defines enum SaltTheme with Colors and Tokens", () => {
    expect(result.swift).toContain("enum SaltTheme {");
    expect(result.swift).toContain("enum Colors {");
    expect(result.swift).toContain("enum Tokens {");
  });

  it("swift contains light and dark section comments", () => {
    expect(result.swift).toContain("// ─── Light mode");
    expect(result.swift).toContain("// ─── Dark mode");
  });

  it("header does not appear in light or dark fields", () => {
    expect(result.light).not.toContain("Generated by");
    expect(result.dark).not.toContain("Generated by");
  });
});

// ─── Light mode ──────────────────────────────────────────────────────

describe("generateSwiftUITheme — light constants", () => {
  it("primary is Color(red:green:blue:) format", () => {
    expect(result.light).toMatch(/static let primary = Color\(red: [\d.]+, green: [\d.]+, blue: [\d.]+\)/);
  });

  it("contains all 26 semantic color constants (no suffix)", () => {
    const expected = [
      "primary", "secondary", "tertiary", "quaternary",
      "background", "surface", "text", "muted", "border", "input", "ring",
      "danger", "success", "warning", "info",
      "onPrimary", "onSecondary", "onTertiary", "onQuaternary",
      "onBackground", "onSurface", "onMuted",
      "onDanger", "onSuccess", "onWarning", "onInfo",
    ];
    for (const name of expected) {
      expect(result.light).toContain(`static let ${name} =`);
    }
  });

  it("surface elevation vars use surfaceCard naming", () => {
    expect(result.light).toContain("static let surfaceCard =");
    expect(result.light).toContain("static let surfacePopover =");
  });

  it("state vars use intentState naming (primaryHover etc.)", () => {
    expect(result.light).toContain("static let primaryHover =");
    expect(result.light).toContain("static let dangerDisabled =");
  });

  it("light vars have no Dark suffix", () => {
    expect(result.light).not.toContain("Dark =");
  });
});

// ─── Dark mode ───────────────────────────────────────────────────────

describe("generateSwiftUITheme — dark constants", () => {
  it("dark primary has Dark suffix", () => {
    expect(result.dark).toMatch(/static let primaryDark = Color\(red: [\d.]+, green: [\d.]+, blue: [\d.]+\)/);
  });

  it("dark background differs from light background", () => {
    const lBg = result.light.match(/static let background = (Color\([^)]+\))/)?.[1];
    const dBg = result.dark.match(/static let backgroundDark = (Color\([^)]+\))/)?.[1];
    expect(lBg).toBeDefined();
    expect(dBg).toBeDefined();
    expect(lBg).not.toBe(dBg);
  });

  it("dark does not contain token constants", () => {
    expect(result.dark).not.toContain("static let spacing");
    expect(result.dark).not.toContain("static let radius");
  });
});

// ─── Token constants ─────────────────────────────────────────────────

describe("generateSwiftUITheme — token constants", () => {
  it("dart contains spacingMd as CGFloat", () => {
    expect(result.swift).toMatch(/static let spacingMd: CGFloat = \d+/);
  });

  it("swift contains radius as CGFloat", () => {
    expect(result.swift).toMatch(/static let radius\w+: CGFloat = \d+/);
  });

  it("swift contains fontSize as CGFloat", () => {
    expect(result.swift).toMatch(/static let fontSize\w+: CGFloat = \d+/);
  });

  it("swift contains fontSizeBase", () => {
    expect(result.swift).toContain("static let fontSizeBase: CGFloat =");
  });

  it("swift contains fontWeight as Font.Weight", () => {
    expect(result.swift).toMatch(/static let fontWeight\w+: Font\.Weight = \.init\(rawValue: \d+\)/);
  });

  it("swift contains lineHeight as CGFloat", () => {
    expect(result.swift).toMatch(/static let lineHeight\w+: CGFloat = [\d.]+/);
  });
});

// ─── enumName option ─────────────────────────────────────────────────

describe("generateSwiftUITheme — enumName option", () => {
  it("custom enumName replaces SaltTheme", () => {
    const { swift } = generateSwiftUITheme(theme, { enumName: "AppTheme" });
    expect(swift).toContain("enum AppTheme {");
    expect(swift).not.toContain("enum SaltTheme");
  });

  it("header shows enumName when non-default", () => {
    const { swift } = generateSwiftUITheme(theme, { enumName: "AppTheme" });
    expect(swift).toContain('enumName="AppTheme"');
  });
});

// ─── Consistency ─────────────────────────────────────────────────────

describe("generateSwiftUITheme — consistency", () => {
  it("light and dark are consistent across calls", () => {
    const r1 = generateSwiftUITheme(theme);
    const r2 = generateSwiftUITheme(theme);
    expect(r1.light).toBe(r2.light);
    expect(r1.dark).toBe(r2.dark);
  });

  it("all presets produce valid swift output", () => {
    const presets = ["peacock", "ocean", "forest", "desert"] as const;
    for (const preset of presets) {
      const t = generateTheme({ preset });
      const { swift } = generateSwiftUITheme(t);
      expect(swift).toContain("enum SaltTheme");
      expect(swift).toContain("static let primary =");
    }
  });
});
